import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import {
  compileSeoGeoExecution,loadSeoGeoExecutionSources,validateSeoGeoExecutionSources
} from '../lib/search-geo-execution.mjs';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const context=JSON.parse(fs.readFileSync(path.join(root,'examples/search-geo-owner-context.example.json'),'utf8'));
const sources=loadSeoGeoExecutionSources();
const contract=validateSeoGeoExecutionSources(sources);
assert.equal(contract.opportunityCount,34);
assert.equal(sources.policy.records.length,34);
assert.deepEqual(sources.policy.records.map(r=>r.id),sources.research.opportunities.map(o=>o.id));
assert.deepEqual(contract.factKeys.sort(),Object.keys(context.facts).sort());
const result=compileSeoGeoExecution(context,{sources});
assert.equal(result.kind,'seo-geo-research-execution-plan');
assert.equal(result.summary.total,34);
assert.deepEqual(result.summary.byPriority,{P0:7,P1:19,P2:8});
assert.equal(result.noAutomaticTargetMutation,true);
assert.equal(result.noRankingPromise,true);
assert.equal(result.noInventedOwnerResults,true);
assert.equal(result.opportunities.length,34);
assert(result.opportunities.every(row=>row.claimOfSearchOutcome===false&&row.claimOfCompletedImplementation===false));
assert(result.opportunities.every(row=>row.existingOwnerPathObserved),'every rule must point to a real existing source/tool, not a planned imaginary module');
const find=id=>result.opportunities.find(row=>row.id===id);
assert.equal(find('versioned-search-source-redirect-gate').executionState,'local-review-available');
assert.equal(find('october-ai-copy-editorial-gate').executionState,'local-review-available');
assert.equal(find('source-backed-bing-grounding-map').executionState,'awaiting-owner-facts');
assert.equal(find('bing-citation-share-by-grounding-query').executionState,'awaiting-owner-facts');
assert.equal(find('google-video-creator-and-author-parity').executionState,'not-applicable-to-declared-site');
assert.equal(find('openai-acp-commerce-feed').executionState,'not-applicable-to-declared-site');
assert.equal(find('ugc-fresh-data-qualification').executionState,'not-applicable-to-declared-site');
assert.equal(find('eea-vss-aggregator-eligibility').executionState,'not-applicable-to-declared-site');
assert.equal(find('webmcp-real-form-progressive').executionState,'not-applicable-to-declared-site');
assert.equal(find('ietf-ai-preference-header-watch').executionState,'watch-only');
assert.equal(find('cloudflare-policy-aware-incremental-crawl').executionState,'not-applicable-to-declared-site');
const b=structuredClone(context);
b.facts.hasBingOwnerEvidence=true;
assert.equal(compileSeoGeoExecution(b,{sources}).opportunities.find(row=>row.id==='bing-intent-preview').executionState,'requires-owner-review');
b.ownerReviewed=true;
assert.equal(compileSeoGeoExecution(b,{sources}).opportunities.find(row=>row.id==='bing-intent-preview').executionState,'owner-evidence-review-ready');
b.facts.hasRealCommerceCatalog=true;
b.facts.hasApprovedAcpFeedAccess=false;
const gated=compileSeoGeoExecution(b,{sources});
assert.equal(gated.opportunities.find(row=>row.id==='openai-acp-commerce-feed').executionState,'program-approval-not-granted');
b.facts.hasApprovedAcpFeedAccess=true;
assert.equal(compileSeoGeoExecution(b,{sources}).opportunities.find(row=>row.id==='acp-stable-schema-variants').executionState,'partner-approval-check');
b.facts.hasRealUserForm=true;b.facts.hasWebMcpOriginTrialAccess=true;
assert.equal(compileSeoGeoExecution(b,{sources}).opportunities.find(row=>row.id==='webmcp-agent-task-evals-security').executionState,'sandbox-only');
b.facts.hasPublishedVideo=true;
assert.equal(compileSeoGeoExecution(b,{sources}).opportunities.find(row=>row.id==='google-video-creator-and-author-parity').executionState,'eligible-for-bounded-implementation-review');

const bad=x=>{const c=structuredClone(context);x(c);return c;};
assert.throws(()=>compileSeoGeoExecution(bad(x=>{x.facts.hasBingOwnerEvidence='yes';}),{sources}),/non-boolean/);
assert.throws(()=>compileSeoGeoExecution(bad(x=>{x.facts.untrackedSensitiveValue=true;}),{sources}),/Unexpected/);
assert.throws(()=>compileSeoGeoExecution(bad(x=>{x.site='http://example.com/';}),{sources}),/HTTPS/);
assert.throws(()=>compileSeoGeoExecution(bad(x=>{x.ownerReviewed='true';}),{sources}),/boolean\/null/);
const duplicated=structuredClone(sources);duplicated.policy.records.push({...duplicated.policy.records[0]});
assert.throws(()=>validateSeoGeoExecutionSources(duplicated),/duplicate|Unexpected/);
const missing=structuredClone(sources);missing.policy.records.pop();
assert.throws(()=>validateSeoGeoExecutionSources(missing),/every researched|exactly one/);

const temp=fs.mkdtempSync(path.join(os.tmpdir(),'goose-geo-plan-'));
try{
  const input=path.join(temp,'context.json'),out=path.join(temp,'plan.json');
  fs.writeFileSync(input,JSON.stringify(context));
  const cmd=path.join(root,'bin/arwp-geo-plan.mjs');
  const run=(...args)=>spawnSync(process.execPath,[cmd,...args],{encoding:'utf8',cwd:root});
  let r=run('--context='+input,'--json','--output='+out);
  assert.equal(r.status,0,r.stderr);
  assert.equal(JSON.parse(r.stdout).summary.total,34);
  assert.equal(JSON.parse(fs.readFileSync(out,'utf8')).noRankingPromise,true);
  r=run('--context='+input,'--output='+out);
  assert.equal(r.status,2,'previous owner decision plans must be immutable by default');
}finally{fs.rmSync(temp,{recursive:true,force:true})}
console.log('PASS all 34 candidate action gates, owner false/unknown/approval, sandbox limits and no synthetic SEO score');
